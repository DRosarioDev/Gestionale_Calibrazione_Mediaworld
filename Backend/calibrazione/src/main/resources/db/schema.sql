-- =====================================================================
-- Gestionale Calibrazione - schema PostgreSQL
-- =====================================================================
-- Lo script e' idempotente: viene eseguito
--   * dal container PostgreSQL, montato in docker-entrypoint-initdb.d
--     (solo al primo avvio, quando il volume dati e' vuoto);
--   * da Spring Boot a ogni avvio con il profilo "postgres"
--     (spring.sql.init.mode=always).
--
-- Per questo motivo ogni istruzione usa IF NOT EXISTS: non distrugge
-- i dati esistenti. Le modifiche strutturali future andranno applicate
-- con una migrazione dedicata (es. Flyway) e non modificando i tipi qui.
--
-- Convenzioni:
--   * id numerici generati dal database (identity);
--   * enum Java salvati come VARCHAR con il nome esatto dell'enum;
--   * timestamp locali (LocalDateTime nel model) senza timezone;
--   * nessun campo punto vendita: il gestionale copre solo Arese.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Utenti
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS utenti (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(100) NOT NULL,
    cognome        VARCHAR(100) NOT NULL,
    email          VARCHAR(160) NOT NULL,
    password       VARCHAR(100) NOT NULL,
    ruolo          VARCHAR(20)  NOT NULL CHECK (ruolo IN ('ADMIN', 'TECNICO')),
    attivo         BOOLEAN      NOT NULL DEFAULT TRUE,
    data_creazione TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- L'email e' univoca senza distinzione tra maiuscole e minuscole.
CREATE UNIQUE INDEX IF NOT EXISTS ux_utenti_email ON utenti (LOWER(email));

-- ---------------------------------------------------------------------
-- Calibrazioni
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS calibrazioni (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_calibrazione TIMESTAMP    NOT NULL,
    tecnico           VARCHAR(200) NOT NULL,
    note              TEXT,
    -- Report .txt personalizzato dal tecnico dopo la calibrazione.
    report            TEXT
);

-- Migrazione idempotente per i database creati prima dell'introduzione
-- del report personalizzato.
ALTER TABLE calibrazioni ADD COLUMN IF NOT EXISTS report TEXT;

-- ---------------------------------------------------------------------
-- Televisioni
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS televisori (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca             VARCHAR(30)  NOT NULL
        CHECK (marca IN ('SAMSUNG', 'LG', 'SONY', 'PHILIPS', 'PANASONIC', 'TOSHIBA',
                         'HISENSE', 'SHARP', 'VIZIO', 'TCL', 'ALTRO')),
    modello           VARCHAR(200) NOT NULL,
    codice_seriale    VARCHAR(100) NOT NULL,
    pollici           INTEGER      NOT NULL CHECK (pollici BETWEEN 10 AND 150),
    tecnologia        VARCHAR(30)  NOT NULL
        CHECK (tecnologia IN ('UHD', 'OLED', 'QLED', 'NEO_QLED', 'MINI_LED', 'LED',
                              'MICRO_LED', 'LCD', 'PLASMA', 'ALTRO')),
    stato             VARCHAR(30)  NOT NULL
        CHECK (stato IN ('DA_CALIBRARE', 'IN_CALIBRAZIONE', 'CALIBRATO')),
    data_aggiunta     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_calibrazione TIMESTAMP,
    -- Nome completo del tecnico che ha registrato la TV: snapshot leggibile,
    -- coerente con il campo "aggiuntoDa" del contratto API.
    aggiunto_da       VARCHAR(200) NOT NULL,
    note              TEXT,
    -- Relazione 1-a-1 opzionale con la calibrazione.
    -- ON DELETE SET NULL permette di eliminare la calibrazione senza
    -- dover prima azzerare manualmente la televisione.
    calibrazione_id   BIGINT UNIQUE REFERENCES calibrazioni (id) ON DELETE SET NULL
);

-- Il service salva il seriale in maiuscolo, l'indice ne garantisce
-- comunque l'unicita' indipendentemente dal case.
-- Il seriale e' opzionale: l'indice ignora i valori vuoti, cosi' piu'
-- televisioni possono essere registrate senza codice seriale.
DROP INDEX IF EXISTS ux_televisori_seriale;
CREATE UNIQUE INDEX IF NOT EXISTS ux_televisori_seriale
    ON televisori (UPPER(codice_seriale))
    WHERE codice_seriale <> '';
CREATE INDEX IF NOT EXISTS ix_televisori_stato ON televisori (stato);
CREATE INDEX IF NOT EXISTS ix_televisori_data_aggiunta ON televisori (data_aggiunta DESC);

-- ---------------------------------------------------------------------
-- Valori della calibrazione (1-a-1 con calibrazione)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS calibrazione_valori (
    calibrazione_id BIGINT PRIMARY KEY REFERENCES calibrazioni (id) ON DELETE CASCADE,
    bianco_gain_r   INTEGER NOT NULL DEFAULT 0 CHECK (bianco_gain_r BETWEEN -50 AND 50),
    bianco_gain_g   INTEGER NOT NULL DEFAULT 0 CHECK (bianco_gain_g BETWEEN -50 AND 50),
    bianco_gain_b   INTEGER NOT NULL DEFAULT 0 CHECK (bianco_gain_b BETWEEN -50 AND 50),
    bianco_offset_r INTEGER NOT NULL DEFAULT 0 CHECK (bianco_offset_r BETWEEN -50 AND 50),
    bianco_offset_g INTEGER NOT NULL DEFAULT 0 CHECK (bianco_offset_g BETWEEN -50 AND 50),
    bianco_offset_b INTEGER NOT NULL DEFAULT 0 CHECK (bianco_offset_b BETWEEN -50 AND 50),
    colori_abilitati BOOLEAN NOT NULL DEFAULT FALSE
);

-- Migrazione: la modalita' RGB/HSL non esiste piu', i colori sono salvati
-- direttamente come i tre valori inseriti nella TV.
ALTER TABLE calibrazione_valori DROP COLUMN IF EXISTS modalita_colore;

-- ---------------------------------------------------------------------
-- Parametri liberi (etichetta/valore) della calibrazione
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS calibrazione_parametri (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calibrazione_id BIGINT       NOT NULL REFERENCES calibrazioni (id) ON DELETE CASCADE,
    ordine          INTEGER      NOT NULL DEFAULT 0,
    etichetta       VARCHAR(80)  NOT NULL,
    valore          VARCHAR(120)
);

CREATE INDEX IF NOT EXISTS ix_calibrazione_parametri
    ON calibrazione_parametri (calibrazione_id, ordine);

-- ---------------------------------------------------------------------
-- Colori RGBCMY della calibrazione (una riga per colore)
-- Ogni colore ha esattamente i tre valori che il tecnico inserisce nella
-- TV: nessuna conversione RGB/HSL e nessun limite di intervallo.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS calibrazione_colori (
    calibrazione_id BIGINT      NOT NULL REFERENCES calibrazioni (id) ON DELETE CASCADE,
    chiave          VARCHAR(10) NOT NULL
        CHECK (chiave IN ('rosso', 'verde', 'blu', 'ciano', 'magenta', 'giallo')),
    valore1         INTEGER NOT NULL,
    valore2         INTEGER NOT NULL,
    valore3         INTEGER NOT NULL,
    PRIMARY KEY (calibrazione_id, chiave)
);

-- Migrazione idempotente dal vecchio schema RGB/HSL.
ALTER TABLE calibrazione_colori ADD COLUMN IF NOT EXISTS valore1 INTEGER NOT NULL DEFAULT 0;
ALTER TABLE calibrazione_colori ADD COLUMN IF NOT EXISTS valore2 INTEGER NOT NULL DEFAULT 0;
ALTER TABLE calibrazione_colori ADD COLUMN IF NOT EXISTS valore3 INTEGER NOT NULL DEFAULT 0;
ALTER TABLE calibrazione_colori DROP COLUMN IF EXISTS rgb_r;
ALTER TABLE calibrazione_colori DROP COLUMN IF EXISTS rgb_g;
ALTER TABLE calibrazione_colori DROP COLUMN IF EXISTS rgb_b;
ALTER TABLE calibrazione_colori DROP COLUMN IF EXISTS hsl_h;
ALTER TABLE calibrazione_colori DROP COLUMN IF EXISTS hsl_s;
ALTER TABLE calibrazione_colori DROP COLUMN IF EXISTS hsl_l;
